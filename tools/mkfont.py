def rows(ch):
    art = [ln for ln in GLYPHS.get(ch, "").strip("\n").split("\n") if ln]
    bits = []
    for line in art:
        v = 0
        for i, c in enumerate(line[:5]):
            if c == "#":
                v |= 1 << (4 - i)
        bits.append(v)
    while len(bits) < 7:
        bits.append(0)
    return bits


def main():
    print(";")
    print("; font.s - 5x7 bitmap font for the HIRES screens (generated by")
    print("; tools/mkfont.py).  One glyph is seven bytes, one per row, each")
    print("; row shifted into the six pixel cell the way the screen wants it:")
    print("; bit 5 is the leftmost pixel and bit 0 is the gap column.  Laying")
    print("; the table out like this costs a byte a row over the old packed")
    print("; form, and saves the blitter two shifts and a mask per row.")
    print(";")
    print("        .export         _font6")
    print("")
    print("        .rodata")
    print("_font6:")

    for code in range(32, 96):
        ch = chr(code)
        g = [(v & 0x1F) << 1 for v in rows(ch)]
        print("        .byte   " + ", ".join("$%02X" % v for v in g) +
              "        ; '%s'" % ("'" if ch == "'" else ch))

    # HIRES pixel helpers: the byte x falls in, the pixel within it, and
    # the bit masks used by the line and column blitters.
    print("")
    print("        .export         _xmask, _mfrom, _mto")
    print("_xmask:                 ; bit for pixel x%6, leftmost first")
    print("        .byte   " + ", ".join(
        "$%02X" % (0x20 >> i) for i in range(6)))
    print("_mfrom:                 ; bits from x%6 down to the byte edge")
    print("        .byte   " + ", ".join(
        "$%02X" % (0x3F >> i) for i in range(6)))
    print("_mto:                   ; bits from the byte edge to x%6")
    print("        .byte   " + ", ".join(
        "$%02X" % ((0x3F << (5 - i)) & 0x3F) for i in range(6)))


if __name__ == "__main__":
    main()
